"""Find code entry points reachable only through data pointers (vtable stubs etc.).

Every aligned big-endian word in .rdata/.data that points into .text/BINK at an address *not covered by any
.pdata range* is a candidate. Emits TOML `[functions]` lines (`{}` = let analysis size them).
Pointers into the middle of .pdata functions are ignored (jump-table labels, catch targets...).

usage: find_ptr_funcs.py <default.pe> [out.toml]
"""
import bisect, struct, sys

BASE = 0x82000000
pe = open(sys.argv[1], 'rb').read()
off = struct.unpack_from('<I', pe, 0x3C)[0]
nsec, optsz = struct.unpack_from('<H', pe, off + 6)[0], struct.unpack_from('<H', pe, off + 20)[0]
secs = {}
s = off + 24 + optsz
for _ in range(nsec):
    name = pe[s:s + 8].split(b'\0')[0].decode()
    vsz, va = struct.unpack_from('<II', pe, s + 8)
    secs[name] = (BASE + va, vsz)
    s += 40

code = [secs['.text'], secs['BINK']]
pva, psz = secs['.pdata']
ranges = []
for o in range(pva - BASE, pva - BASE + psz, 8):
    st, info = struct.unpack_from('>II', pe, o)
    if st:
        ranges.append((st, st + ((info >> 8) & 0x3FFFFF) * 4))
ranges.sort()
starts = [r[0] for r in ranges]

def in_code(a):
    return any(b <= a < b + n for b, n in code)

def covered(a):
    i = bisect.bisect_right(starts, a) - 1
    return i >= 0 and a < ranges[i][1]

def looks_like_code(a):
    w = struct.unpack_from('>I', pe, a - BASE)[0]
    return w != 0 and (w >> 26) != 0

found = {}
for sec in ('.rdata', '.data'):
    va, sz = secs[sec]
    for o in range(va - BASE, va - BASE + sz - 3, 4):
        p = struct.unpack_from('>I', pe, o)[0]
        if p & 3 or not in_code(p) or covered(p) or not looks_like_code(p):
            continue
        found.setdefault(p, []).append(BASE + o)

lines = [f'0x{a:08X} = {{}}  # {len(refs)} ref(s), first from 0x{refs[0]:08X}'
         for a, refs in sorted(found.items())]
print(f'{len(found)} pointer-only entry points outside .pdata', file=sys.stderr)
out = '\n'.join(lines) + '\n'
if len(sys.argv) > 2:
    open(sys.argv[2], 'w', newline='\n').write(
        '# Generated by scripts/find_ptr_funcs.py: code reached only via data pointers, not in .pdata.\n'
        '[functions]\n' + out)
else:
    sys.stdout.write(out)
